#!/usr/bin/env bash
# Shared helpers for the local dev cluster scripts. Source, don't execute.
set -euo pipefail

LOCAL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck disable=SC2034  # used by the scripts that source this file
REPO_DIR="$(cd "${LOCAL_DIR}/../.." && pwd)"
# shellcheck disable=SC2034  # used by the scripts that source this file
SECRETS_DIR="${LOCAL_DIR}/.secrets"

# shellcheck source=../versions.env
source "${LOCAL_DIR}/versions.env"

KUBE_CONTEXT="kind-${KIND_CLUSTER_NAME}"

# Bifrost admin user; its password is generated into ${SECRETS_DIR}.
# shellcheck disable=SC2034  # used by the scripts that source this file
BIFROST_ADMIN_USER="admin"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m  ✓\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m  !\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m  ✗\033[0m %s\n' "$*" >&2; exit 1; }

require_cmd() {
  local cmd
  for cmd in "$@"; do
    command -v "$cmd" >/dev/null 2>&1 || die "'$cmd' not found on PATH. See deploy/local/README.md#prerequisites"
  done
}

require_docker_running() {
  docker info >/dev/null 2>&1 || die "Docker is not running. Start Docker Desktop or OrbStack and retry."
}

# kubectl / helm pinned to the kind context so a stray current-context is never touched.
k() { kubectl --context "${KUBE_CONTEXT}" "$@"; }
h() { helm --kube-context "${KUBE_CONTEXT}" "$@"; }

# Prints "<chart>-<version>" of the most recent successfully deployed revision of a
# Helm release, or nothing. Uses history so a later failed upgrade attempt does
# not hide a working install.
release_chart() {
  local ns="$1" name="$2"
  h -n "$ns" history "$name" -o json 2>/dev/null \
    | python3 -c 'import json,sys
d=[r for r in json.load(sys.stdin) if r.get("status") in ("deployed","superseded")]
print(d[-1]["chart"] if d else "")' 2>/dev/null || true
}

cluster_exists() {
  kind get clusters 2>/dev/null | grep -qx "${KIND_CLUSTER_NAME}"
}

# Replace ${VAR} placeholders with values from versions.env (portable; no envsubst).
render() {
  local file="$1"
  sed -e "s|\${JAEGER_IMAGE}|${JAEGER_IMAGE}|g" \
      -e "s|\${CURL_IMAGE}|${CURL_IMAGE}|g" \
      -e "s|\${MOCK_LLM_IMAGE}|${MOCK_LLM_IMAGE}|g" \
      "$file"
}

# retry <attempts> <command...>: re-run a flaky network command with backoff.
retry() {
  local attempts="$1" n=1; shift
  until "$@"; do
    if ((n >= attempts)); then return 1; fi
    warn "attempt ${n}/${attempts} failed: $*; retrying in $((n * 3))s"
    sleep $((n * 3)); n=$((n + 1))
  done
}

add_helm_repos() {
  retry 3 helm repo add projectcalico https://docs.tigera.io/calico/charts --force-update >/dev/null
  retry 3 helm repo add bifrost https://maximhq.github.io/bifrost/helm-charts --force-update >/dev/null
  retry 3 helm repo add open-telemetry https://open-telemetry.github.io/opentelemetry-helm-charts --force-update >/dev/null
  retry 3 helm repo update projectcalico bifrost open-telemetry >/dev/null
}

random_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }

# Service URL of the in-cluster mock LLM (tools/mock-llm).
MOCK_LLM_URL="http://mock-llm.mock-llm.svc.cluster.local:8080"

# Writes Bifrost's generated values (providers + dev virtual key) to stdout.
# The "mock" provider (in-cluster mock LLM) is always configured. Real providers
# are added only when their API key is in the environment, and are referenced
# as env.<NAME>, never inlined.
bifrost_generated_values() {
  local vk="$1"
  local configured=(mock)
  echo "# Generated by scripts/up.sh. Do not commit."
  echo "bifrost:"
  echo "  providers:"
  echo "    mock:"
  echo "      custom_provider_config:"
  echo "        base_provider_type: openai"
  echo "      network_config:"
  echo "        base_url: ${MOCK_LLM_URL}"
  echo "        allow_private_network: true   # ClusterIP is an RFC 1918 address"
  echo "      keys:"
  echo "        - name: mock-dev"
  echo "          value: mock-not-a-secret"
  echo "          weight: 1"
  echo "          models: [\"*\"]"
  if [[ -n "${ANTHROPIC_API_KEY:-}" ]]; then
    configured+=(anthropic)
    echo "    anthropic:"
    echo "      keys:"
    echo "        - name: anthropic-dev"
    echo "          value: env.ANTHROPIC_API_KEY"
    echo "          weight: 1"
    echo "          models: [\"*\"]"
  fi
  if [[ -n "${OPENAI_API_KEY:-}" ]]; then
    configured+=(openai)
    echo "    openai:"
    echo "      keys:"
    echo "        - name: openai-dev"
    echo "          value: env.OPENAI_API_KEY"
    echo "          weight: 1"
    echo "          models: [\"*\"]"
  fi
  echo "  governance:"
  echo "    virtualKeys:"
  echo "      - id: vk-agentory-dev"
  echo "        name: agentory-dev"
  echo "        description: Local development key used by smoke tests"
  echo "        value: ${vk}"
  echo "        is_active: true"
  # allow_all_providers alone permits no models; each provider needs an explicit
  # entry with allowed models and provider keys (verified against Bifrost v2.3.1).
  echo "        provider_configs:"
  local p
  for p in "${configured[@]}"; do
    echo "          - provider: ${p}"
    echo "            weight: 1.0"
    echo "            allowed_models: [\"*\"]"
    echo "            key_ids: [\"*\"]"
  done
}
