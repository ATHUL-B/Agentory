#!/usr/bin/env bash
# Shared helpers for the local dev cluster scripts. Source, don't execute.
set -euo pipefail

LOCAL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck disable=SC2034  # used by the scripts that source this file
SECRETS_DIR="${LOCAL_DIR}/.secrets"

# shellcheck source=../versions.env
source "${LOCAL_DIR}/versions.env"

KUBE_CONTEXT="kind-${KIND_CLUSTER_NAME}"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m  ✓\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m  !\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m  ✗\033[0m %s\n' "$*" >&2; exit 1; }

require_cmd() {
  local cmd
  for cmd in "$@"; do
    command -v "$cmd" >/dev/null 2>&1 || die "'$cmd' not found on PATH. See deploy/local/README.md#prerequisites"
  done
}

require_docker_running() {
  docker info >/dev/null 2>&1 || die "Docker is not running. Start Docker Desktop or OrbStack and retry."
}

# kubectl / helm pinned to the kind context so a stray current-context is never touched.
k() { kubectl --context "${KUBE_CONTEXT}" "$@"; }
h() { helm --kube-context "${KUBE_CONTEXT}" "$@"; }

cluster_exists() {
  kind get clusters 2>/dev/null | grep -qx "${KIND_CLUSTER_NAME}"
}

# Replace ${VAR} placeholders with values from versions.env (portable; no envsubst).
render() {
  local file="$1"
  sed -e "s|\${JAEGER_IMAGE}|${JAEGER_IMAGE}|g" \
      -e "s|\${CURL_IMAGE}|${CURL_IMAGE}|g" \
      "$file"
}

add_helm_repos() {
  helm repo add projectcalico https://docs.tigera.io/calico/charts --force-update >/dev/null
  helm repo add bifrost https://maximhq.github.io/bifrost/helm-charts --force-update >/dev/null
  helm repo add open-telemetry https://open-telemetry.github.io/opentelemetry-helm-charts --force-update >/dev/null
  helm repo update projectcalico bifrost open-telemetry >/dev/null
}

random_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }

# Writes Bifrost's generated values (providers + dev virtual key) to stdout.
# Only providers whose API key is present in the environment are configured;
# the file references keys as env.<NAME>, never the key itself.
bifrost_generated_values() {
  local vk="$1"
  echo "# Generated by scripts/up.sh. Do not commit."
  echo "bifrost:"
  if [[ -n "${ANTHROPIC_API_KEY:-}" || -n "${OPENAI_API_KEY:-}" ]]; then
    echo "  providers:"
    if [[ -n "${ANTHROPIC_API_KEY:-}" ]]; then
      echo "    anthropic:"
      echo "      keys:"
      echo "        - name: anthropic-dev"
      echo "          value: env.ANTHROPIC_API_KEY"
      echo "          weight: 1"
    fi
    if [[ -n "${OPENAI_API_KEY:-}" ]]; then
      echo "    openai:"
      echo "      keys:"
      echo "        - name: openai-dev"
      echo "          value: env.OPENAI_API_KEY"
      echo "          weight: 1"
    fi
  fi
  echo "  governance:"
  echo "    virtualKeys:"
  echo "      - id: vk-agentory-dev"
  echo "        name: agentory-dev"
  echo "        description: Local development key used by smoke tests"
  echo "        value: ${vk}"
  echo "        is_active: true"
  echo "        allow_all_providers: true"
}
